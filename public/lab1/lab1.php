}

// ==========================================
// Завдання 5: Цикли
// ==========================================

echo "Цикл for (від 1 до 10): ";
for ($i = 1; $i <= 10; $i++) {
    echo $i . " ";
}
echo "<br>";

echo "Цикл while (від 10 до 1): ";
$j = 10;
while ($j >= 1) {
    echo $j . " ";
    $j--;
}
echo "<br><br>";

