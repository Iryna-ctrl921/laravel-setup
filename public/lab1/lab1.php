echo "Hello, World!<br><br>";

// ==========================================
// Завдання 2: Змінні та типи даних
// ==========================================

$strVar = "Текстовий рядок";      // Рядковий тип (string)
$intVar = 42;                     // Ціле число (integer)
$floatVar = 3.1415;               // Число з плаваючою комою (float)
$boolVar = true;                  // Булеве значення (boolean)

// Вивід значень змінних
echo "Значення рядка: $strVar <br>";
echo "Значення цілого числа: $intVar <br>";
echo "Значення числа з комою: $floatVar <br>";
echo "Значення булевої змінної: " . ($boolVar ? 'true' : 'false') . "<br><br>";

// Вивід типу кожної змінної
echo "<strong>Типи даних (var_dump):</strong><br>";
var_dump($strVar); echo "<br>";
var_dump($intVar); echo "<br>";
var_dump($floatVar); echo "<br>";
var_dump($boolVar); echo "<br><br>";

// ==========================================
// Завдання 3: Конкатенація рядків
// ==========================================

$word1 = "Програмування на ";
$word2 = "PHP";
// Об'єднання рядків за допомогою оператора "."
$combinedString = $word1 . $word2;
echo "Результат конкатенації: " . $combinedString . "<br><br>";

